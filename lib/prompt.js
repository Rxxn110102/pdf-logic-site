// 提示词集中放在服务器端，前端只能提交文档文字，不能把接口当作通用聊天代理使用。

export function buildAnalyzePrompt(docText, fileName) {
  return `你是一名严谨的文档分析师。请阅读下面从 PDF《${fileName}》中提取的文字，梳理它的知识结构与论证逻辑。
全部用简体中文输出（专有名词可保留原文）。只依据原文，不要编造原文没有的内容。

严格按下面的格式输出，标记行必须原样保留，标记之外不要输出任何其他文字：

<<<MARKDOWN>>>
# 《文档标题》逻辑解析
## 要点
（4-8 条无序列表，概括文档主要内容）
## 核心观点
（作者主张的观点，无序列表，可加粗关键词）
## 采用方法
（研究方法、论证方法、数据或案例来源；若文档不是研究类，写明其组织与论述方式）
## 逻辑推理过程
（有序列表，按推理先后写出：前提/问题 → 依据 → 推论 → 验证，每步用加粗短语开头）
## 主要结论
（无序列表）
<<<MERMAID>>>
flowchart TD
（Mermaid 流程图代码）
<<<END>>>

Mermaid 代码规则（必须遵守，否则无法绘制）：
1. 第一行固定为 flowchart TD，不要用 \`\`\` 包裹。
2. 节点 ID 只用英文字母加数字，如 A1、B2，不要重复定义含义不同的同一 ID。
3. 每个节点文字都用英文双引号包裹，如 A1["研究问题"]；文字内不得出现英文双引号、方括号、竖线或换行，每个不超过 18 个字。
4. 连线用 -->，需要说明关系时写成 A1 -->|"支撑"| B1。
5. 可以用 subgraph 分组：subgraph S1["方法"] 换行写节点 换行 end。
6. 节点总数 8 到 20 个，完整体现：问题或背景 → 方法 → 推理步骤 → 结论。
7. 不要使用 style、classDef、class、click、linkStyle 语句，也不要写注释。

===== 文档文字开始 =====
${docText}
===== 文档文字结束 =====`;
}

export function buildFixPrompt(code, errMsg) {
  return `下面的 Mermaid 流程图代码有语法错误，无法渲染。请修正它，保持原有的节点含义与结构。
规则：第一行为 flowchart TD；节点 ID 只用英文字母和数字；节点文字一律用英文双引号包裹，文字内不含双引号、方括号、竖线；连线标签写成 -->|"文字"|；不要使用 style、classDef、click；不要写注释。
只输出修正后的代码，不要用 \`\`\` 包裹，不要任何解释。

错误信息：
${errMsg}

原代码：
${code}`;
}
